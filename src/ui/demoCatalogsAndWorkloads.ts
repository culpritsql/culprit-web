function makeIndex(opts: {
  schema: string;
  table: string;
  name: string;
  kind: string;
  columns: string[];
  include?: string[];
  filter?: string | null;
  sizeBytes: number;
  seeks: number;
  scans?: number;
  lookups?: number;
  writes: number;
  pk?: boolean;
  unique?: boolean;
  clustered?: boolean;
  rowLockWaitMs?: number;
}): IndexStat {
  const scans = opts.scans ?? 0;
  return partial<IndexStat>({
    schema: opts.schema,
    table: opts.table,
    name: opts.name,
    kind: opts.kind,
    columns: opts.columns,
    include: opts.include ?? [],
    filter: opts.filter ?? null,
    is_primary_key: opts.pk ?? false,
    is_unique: (opts.unique ?? false) || (opts.pk ?? false),
    is_clustered: opts.clustered ?? false,
    is_disabled: false,
    state: null,
    maintained: true,
    has_statistics: true,
    size_bytes: opts.sizeBytes,
    reads: opts.seeks + scans,
    seeks: opts.seeks,
    scans,
    lookups: opts.lookups ?? 0,
    writes: opts.writes,
    last_read: null,
    definition: null,
    contention: opts.rowLockWaitMs
      ? partial({
          row_lock_waits: 148,
          row_lock_wait_ms: opts.rowLockWaitMs,
          page_lock_waits: 12,
          page_lock_wait_ms: 420,
          page_latch_waits: 35,
          page_latch_wait_ms: 290,
          lock_escalations: 2,
        })
      : null,
    mssql_columnstore: null,
    mssql_configuration: null,
    created_at_latest: null,
    partition_of: null,
    opclasses: null,
    counters_since: null,
  });
}

function makeCols(
  schema: string,
  table: string,
  defs: Array<[string, string, boolean?, boolean?, string?]>,
): ColumnInfo[] {
  return defs.map(([name, data_type, nullable = false, generated = false, defVal], idx) => ({
    schema,
    table,
    name,
    data_type,
    nullable,
    default: defVal ?? null,
    generated,
    ordinal: idx + 1,
  }));
}

