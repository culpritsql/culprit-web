interface NodeSpec {
  id: number;
  op: string;
  kind: NodeKind;
  object?: string | null;
  index?: string | null;
  seek?: string | null;
  predicate?: string | null;
  estRows: number;
  actRows: number;
  subtreeCost: number;
  selfCost: number;
  actTimeMs: number;
  warnings?: PlanWarning[];
  children?: NodeSpec[];
}

function toPlanNode(spec: NodeSpec): PlanNode {
  return {
    id: spec.id,
    op: spec.op,
    kind: spec.kind,
    detail: spec.index ?? spec.object ?? null,
    object: spec.object ?? null,
    index: spec.index ?? null,
    seek_predicate: spec.seek ?? null,
    predicate: spec.predicate ?? null,
    est_rows: spec.estRows,
    est_executions: 1,
    act_rows: spec.actRows,
    act_executions: 1,
    rows_read: spec.actRows,
    table_rows: Math.max(spec.actRows, spec.estRows),
    subtree_cost: spec.subtreeCost,
    self_cost: spec.selfCost,
    act_time_ms: spec.actTimeMs,
    runtime: null,
    warnings: spec.warnings ?? [],
    props: {},
    facts: {
      expression_cache: false,
      conditions: [],
      conversions: [],
      user_functions: [],
      columns_without_statistics: [],
      possible_index_names: [],
    },
    children: (spec.children ?? []).map(toPlanNode),
  };
}

function makePlan(
  engine: Engine,
  statement: string,
  root: NodeSpec,
  warnings: PlanWarning[] = [],
): Plan {
  return {
    engine,
    kind: "actual",
    statement,
    total_cost: root.subtreeCost,
    root: toPlanNode(root),
    warnings,
    index_hints: [],
    props: {},
    facts: {
      trigger_timings: [],
      conversions: [],
      changed_columns: [],
    },
    raw: null,
  };
}

