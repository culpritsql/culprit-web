interface QuerySeed {
  id: string;
  text: string;
  total: number;
  mean: number;
  execs: number;
  cpu: number;
  reads: number;
  waitCategory: string;
  waitType: string;
  activePlan: Plan;
  baselinePlan?: { id: string; note: string; plan: Plan };
}

function materializeWorkload(
  base: Workload,
  source: string,
  seeds: QuerySeed[],
): Workload {
  const copy = structuredClone(base);
  copy.source = source;
  const winStart = copy.window_start;
  const winEnd = copy.window_end;

  copy.queries = seeds.map((s, idx) => {
    const template = copy.queries[idx] ?? copy.queries[0]!;
    const variants: PlanVariant[] = s.baselinePlan
      ? [
          partial<PlanVariant>({
            id: s.baselinePlan.id,
            executions: Math.max(120, Math.round(s.execs * 3.4)),
            mean_time_ms: Number(Math.max(0.3, s.mean / 14).toFixed(2)),
            cpu_time_ms: Number(Math.max(0.2, (s.cpu / s.execs) / 12).toFixed(2)),
            logical_reads: Math.max(4, Math.round((s.reads / s.execs) / 22)),
            first_seen: winStart,
            last_seen: winEnd,
          }),
          partial<PlanVariant>({
            id: `${s.id}-active`,
            executions: s.execs,
            mean_time_ms: s.mean,
            cpu_time_ms: Number((s.cpu / s.execs).toFixed(2)),
            logical_reads: Math.round(s.reads / s.execs),
            first_seen: winStart,
            last_seen: winEnd,
          }),
        ]
      : [
          partial<PlanVariant>({
            id: `${s.id}-plan-1`,
            executions: s.execs,
            mean_time_ms: s.mean,
            cpu_time_ms: Number((s.cpu / s.execs).toFixed(2)),
            logical_reads: Math.round(s.reads / s.execs),
            first_seen: winStart,
            last_seen: winEnd,
          }),
        ];

    return partial<QueryStat>({
      ...template,
      id: s.id,
      text: s.text,
      object_name: null,
      total_time_ms: s.total,
      mean_time_ms: s.mean,
      executions: s.execs,
      cpu_time_ms: s.cpu,
      logical_reads: s.reads,
      plan: s.activePlan,
      plan_history: s.baselinePlan
        ? {
            kind: "workload",
            source: { text: `${source} plan history` },
            note: { text: s.baselinePlan.note },
            captured_plan_id: s.baselinePlan.id,
            captured_plan: s.baselinePlan.plan,
          }
        : undefined,
      plans: variants,
      waits: [
        {
          category: s.waitCategory,
          wait_type: s.waitType,
          wait_ms: Math.round(s.total * 0.64),
          tasks: s.execs,
        },
      ],
    });
  });
  copy.query_count = copy.queries.length;
  copy.total_executions = copy.queries.reduce((sum, q) => sum + q.executions, 0);
  return copy;
}

